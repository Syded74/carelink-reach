"""Human review and approval of outreach plans: draft → proposed → reviewed → approved | rejected.

Every change is appended to an audit log that is never rewritten. Approval here is a FICTIONAL
DEMONSTRATION decision: it is not an institutional authorisation and it creates no CHT assignment.
Approved plans are exported for the coordinator, who records each assignment in CHT with the
existing coordination form (CHT assignment integration stays disabled in this prototype).
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import threading
import uuid
from pathlib import Path

PLANNER_ROLES = {"carelink_coordinator", "carelink_supervisor"}
TRANSITIONS = {"submit": ("draft", "proposed"), "review": ("proposed", "reviewed"),
               "approve": ("reviewed", "approved"), "reject": ("reviewed", "rejected")}
DEMO_NOTICE = "FICTIONAL DEMONSTRATION: this decision is not a real institutional authorisation and creates no CHT assignment."


class ApprovalError(PermissionError):
    pass


def _now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")


class Store:
    def __init__(self, directory: str | Path):
        self.dir = Path(directory)
        (self.dir / "proposals").mkdir(parents=True, exist_ok=True)
        self.audit_path = self.dir / "audit.jsonl"
        self._lock = threading.Lock()

    def _path(self, pid: str) -> Path:
        if not all(ch in "0123456789abcdef-" for ch in pid):
            raise ApprovalError("Invalid proposal id")
        return self.dir / "proposals" / f"{pid}.json"

    def _audit(self, event: dict) -> None:
        with self.audit_path.open("a") as f:
            f.write(json.dumps(event, sort_keys=True) + "\n")

    def _save(self, proposal: dict) -> None:
        self._path(proposal["id"]).write_text(json.dumps(proposal, indent=2, sort_keys=True))

    def get(self, pid: str) -> dict:
        path = self._path(pid)
        if not path.exists():
            raise KeyError(pid)
        return json.loads(path.read_text())

    def list(self) -> list[dict]:
        items = [json.loads(p.read_text()) for p in (self.dir / "proposals").glob("*.json")]
        return sorted(items, key=lambda p: p["created_at"], reverse=True)

    def audit(self, pid: str | None = None) -> list[dict]:
        if not self.audit_path.exists():
            return []
        rows = [json.loads(line) for line in self.audit_path.read_text().splitlines() if line.strip()]
        return [r for r in rows if pid is None or r["proposal_id"] == pid]

    def create(self, plan: dict, user: dict) -> dict:
        _require_role(user)
        snapshot = {"dataset_id": plan["dataset_id"], "dataset_sha256": plan["dataset_sha256"], "as_of": plan["as_of"],
                    "demand": plan["demand"], "resources": plan["resources"], "policy": plan["policy"]}
        proposal = {
            "id": str(uuid.uuid4()), "status": "draft", "created_at": _now(), "created_by": user["name"],
            "planner_version": plan["planner_version"], "model_version": plan["model_version"],
            "input_snapshot": snapshot, "input_sha256": hashlib.sha256(json.dumps(snapshot, sort_keys=True).encode()).hexdigest(),
            "plan": plan, "revisions": [], "history": [], "notice": DEMO_NOTICE, "cht_assignment_integration": "disabled",
        }
        with self._lock:
            self._save(proposal)
            self._event(proposal, "create", user, None, "draft", notes="Plan generated by the optimiser")
        return proposal

    def act(self, pid: str, action: str, user: dict, *, notes: str = "", changes: dict | None = None, revised_plan: dict | None = None) -> dict:
        _require_role(user)
        if action not in TRANSITIONS:
            raise ApprovalError(f"Unknown action {action}")
        with self._lock:
            proposal = self.get(pid)
            before, after = TRANSITIONS[action]
            if proposal["status"] != before:
                raise ApprovalError(f"Cannot {action} a plan that is {proposal['status']} (needs {before}).")
            if action == "submit" and user["name"] != proposal["created_by"]:
                raise ApprovalError("Only the person who generated the plan can submit it for review.")
            if action != "submit" and user["name"] == proposal["created_by"]:
                raise ApprovalError("The person who generated a plan cannot review or decide on it (separation of duties).")
            if action in ("approve", "reject") and proposal.get("reviewed_by") and user["name"] != proposal["reviewed_by"]:
                raise ApprovalError("The reviewer who reviewed this plan must record the decision.")
            if action == "reject" and not notes.strip():
                raise ApprovalError("A rejection needs a reason.")
            if revised_plan is not None:
                if action != "review":
                    raise ApprovalError("Changes can only be made during review.")
                proposal["revisions"].append({"at": _now(), "by": user["name"], "changes": changes or {},
                                              "previous_served": proposal["plan"]["result"].get("served"),
                                              "new_served": revised_plan["result"].get("served")})
                proposal["plan"] = revised_plan
            if action == "review":
                proposal["reviewed_by"] = user["name"]
            if action in ("approve", "reject"):
                proposal["decision"] = {"decision": after, "by": user["name"], "at": _now(), "notes": notes, "notice": DEMO_NOTICE}
            proposal["status"] = after
            self._event(proposal, action, user, before, after, notes=notes, changes=changes)
            self._save(proposal)
        return proposal

    def _event(self, proposal, action, user, before, after, *, notes="", changes=None):
        event = {"proposal_id": proposal["id"], "action": action, "from": before, "to": after, "by": user["name"],
                 "roles": sorted(set(user.get("roles", [])) & PLANNER_ROLES), "at": _now(), "notes": notes,
                 "changes": changes or {}, "input_sha256": proposal["input_sha256"], "planner_version": proposal["planner_version"],
                 "model_version": proposal["model_version"]}
        proposal["history"].append(event)
        self._audit(event)


def _require_role(user: dict) -> None:
    if not user or not (set(user.get("roles", [])) & PLANNER_ROLES):
        raise ApprovalError("Only facility coordinators and supervisors can use outreach planning.")

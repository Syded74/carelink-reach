'use strict';
/*
  Builds the CHT UI extension (npm run build-oi-extension): CHT evaluates an extension as one
  CommonJS source, so the lib/ modules it needs (LIBS) are inlined ahead of the tab's code behind a
  minimal require. The properties file
  limits the tab to facility coordinators and supervisors; the data it shows has already been
  limited by CHT replication and the server-side authority rules.
*/
const fs = require('node:fs');
const path = require('node:path');
const district = require('../planning/tolon-district.json');

const root = path.join(__dirname, '..');
const NAME = 'carelink-outreach-intelligence';
// Every lib/ module the tab needs, including what oi-links requires (checked by test/oi-workflow.test.js).
const LIBS = ['schedules', 'workflow', 'mch', 'mch-outreach', 'oi-workflow', 'oi-links'];
const sources = LIBS.map(name => `${JSON.stringify(name)}: function (module, require) {\n${fs.readFileSync(path.join(root, 'lib', `${name}.js`), 'utf8')}\n}`);
const tab = fs.readFileSync(path.join(root, 'ui-extensions-src', `${NAME}.js`), 'utf8');
const out = path.join(root, 'ui-extensions');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, `${NAME}.js`),
  `// Generated by scripts/build-oi-extension.js — edit ui-extensions-src/ and lib/ instead.\n` +
  `const carelinkLib = (function () {\n  const sources = {\n${sources.join(',\n')}\n  };\n  const cache = {};\n` +
  `  const load = name => { const key = name.replace(/^\\.\\//, ''); if (!cache[key]) { const module = { exports: {} }; cache[key] = module; sources[key](module, load); } return cache[key].exports; };\n` +
  `  return load;\n})();\nconst oiWorkflow = carelinkLib('oi-workflow');\nconst oiLinks = carelinkLib('oi-links');\nconst oiMch = carelinkLib('mch');\nconst oiRequests = carelinkLib('workflow');\n${tab}`);
fs.writeFileSync(path.join(out, `${NAME}.properties.json`), JSON.stringify({
  extension_type: 'header_tab', title: 'carelink.oi.tab', icon: 'fa-map-signs', weight: 5,
  roles: ['carelink_coordinator', 'carelink_supervisor'],
  // The tab shows the signed-in user's own facility (carelink_facility_id in the contact summary).
  config: {
    stale_after_days: (district.resource_policy || {}).stale_after_days || 7,
    facilities: Object.fromEntries(district.facilities.map(f => [f.id, {
      name: f.name,
      staff: f.staff.map(({ id, name, role, available }) => ({ id, name, role, available })),
      vehicles: f.vehicles.map(({ id, name, available }) => ({ id, name, available })),
      // Planning values only (labelled simulated/unknown); readiness records in CHT override them in the tab.
      resources: (f.resources || []).map(({ id, name, unit, category, quantity, reserved, status, verified_at }) => ({ id, name, unit, category, quantity, reserved, status, verified_at })),
      // The facility's weekly activity schedule (shown to staff; the planner reads the same configuration).
      calendar: f.outreach_calendar ? { days: f.outreach_calendar.days || {}, enforced: !!f.outreach_calendar.enforced } : null,
    }])),
  },
}, null, 2) + '\n');
console.log(`Built ui-extensions/${NAME}.js`);
